"""Rendering a parameter file as something a person can argue with.

A JSON file of coefficients is auditable but not readable, and a number nobody reads is a number
nobody checks. The report puts each parameter next to the three things needed to judge it -- its
interval, how many laps it rests on, and how much of it is that circuit's own data -- and leads
with the exclusion audit, so the reader knows what was thrown away before seeing what was fitted.

It is regenerated from ``params.json`` alone. Nothing here recomputes a number, so the report and
the file cannot drift apart.
"""

from __future__ import annotations

from apex.calibrate.estimates import Estimate
from apex.calibrate.pace import PaceModel
from apex.calibrate.params import ParameterSet

__all__ = ["render_report"]


def _interval(estimate: Estimate, places: int = 4, *, signed: bool = True) -> str:
    """Format an interval, showing signs only where the quantity can actually be negative.

    A pit loss of "+22.54" reads as a change rather than a duration; a degradation slope without
    its sign hides the one thing a reader is checking.
    """
    if estimate.interval is None:
        return "(no interval: too few independent observations)"
    low, high = estimate.interval
    sign = "+" if signed else ""
    return f"[{low:{sign}.{places}f}, {high:{sign}.{places}f}]"


def _weight(estimate: Estimate) -> str:
    if estimate.shrinkage is None:
        return "—"
    return "pooled" if estimate.shrinkage == 0.0 else f"{estimate.shrinkage:.2f}"


def _pace_section(pace: PaceModel) -> list[str]:
    lines = [
        "| Compound | Offset vs " + pace.reference_compound + " (s) | Degradation (s/lap) |"
        " Curvature (s/lap²) | Laps |",
        "|---|---|---|---|---|",
    ]
    for entry in pace.degradation:
        offset = (
            "reference"
            if entry.offset_s is None
            else (f"{entry.offset_s.value:+.3f} {_interval(entry.offset_s, 3)}")
        )
        linear = entry.coefficients[0]
        curvature = (
            f"{entry.coefficients[1].value:+.5f} {_interval(entry.coefficients[1], 5)}"
            if len(entry.coefficients) > 1
            else "—"
        )
        lines.append(
            f"| {entry.compound} | {offset} | {linear.value:+.4f} {_interval(linear)} |"
            f" {curvature} | {linear.n_obs:,} |"
        )
    return lines


def render_report(params: ParameterSet) -> str:
    """Render the whole parameter set as Markdown."""
    provenance = params.provenance
    lines: list[str] = [
        "# Calibration report",
        "",
        "Generated by `apex calibrate` from `params/params.json`. Every number here is fitted",
        "from real race telemetry and carries an interval; nothing is hand-set.",
        "",
        "## Provenance",
        "",
        f"- **Generated** {provenance.generated_at:%Y-%m-%d %H:%M} UTC by APEX"
        f" {provenance.apex_version}",
        f"- **Trained on** seasons {list(provenance.seasons)}"
        f" — {provenance.n_races} dry races at {provenance.n_circuits} circuits",
        f"- **Held out** seasons {list(provenance.holdout_seasons)}, which no number here has seen",
        f"- **Config hash** `{provenance.config_hash}`, **seed** `{provenance.seed}`",
        f"- **Laps** {provenance.n_laps_used:,} used of {provenance.n_laps_available:,} available"
        f" ({provenance.retained_fraction:.1%})",
        "",
        "## What the exclusion rules removed",
        "",
        "Attributed in pipeline order: a lap removed as an in-lap is not counted again as a",
        "safety-car lap.",
        "",
        "| Rule | Laps removed | Remaining |",
        "|---|---|---|",
    ]
    lines += [
        f"| `{entry.rule}` | {entry.removed:,} | {entry.remaining:,} |"
        for entry in params.exclusions
    ]

    pace = params.pace
    lines += [
        "",
        "## Pace",
        "",
        f"Fitted on {pace.n_laps:,} laps from {pace.n_races} races and {pace.n_cars} car-races,",
        f"with a residual standard deviation of {pace.residual_std_s:.3f} s and a within-car",
        f"R² of {pace.r_squared_within:.3f}.",
        "",
        "### Tyre degradation and compound offsets",
        "",
        *_pace_section(pace),
        "",
        "### Race conditions",
        "",
        "| Effect | Estimate | Interval | Laps |",
        "|---|---|---|---|",
        f"| Race progress (fuel and track evolution, start to finish) |"
        f" {pace.fuel_effect_s.value:+.3f} s | {_interval(pace.fuel_effect_s, 3)} |"
        f" {pace.fuel_effect_s.n_obs:,} |",
        f"| Dirty air, directly behind a car | {pace.dirty_air_s.value:+.3f} s |"
        f" {_interval(pace.dirty_air_s, 3)} | {pace.dirty_air_s.n_obs:,} |",
        "",
        f"The dirty-air penalty decays with a time constant of {pace.dirty_air_saturation_s:.1f} s:"
        f" {pace.dirty_air_penalty(1.0):.3f} s at a one-second gap,"
        f" {pace.dirty_air_penalty(3.0):.3f} s at three.",
        "",
        "### Variation between circuits",
        "",
        "Standard deviation of each coefficient across circuits, after partial pooling. A zero",
        "means the circuits disagreed no more than their own noise explains, so every circuit",
        "takes the pooled value — a finding about how much this window of data can resolve,",
        "not a missing number.",
        "",
        "| Coefficient | Between-circuit SD |",
        "|---|---|",
    ]
    lines += [
        f"| `{name}` | {value:.4f} |"
        for name, value in sorted(params.between_circuit_std.items(), key=lambda kv: -kv[1])
    ]

    pit = params.pit_loss
    lines += [
        "",
        "## Pit loss",
        "",
        f"Measured from {pit.n_stops:,} green-flag stops across {pit.n_races} races."
        f" {pit.excluded_under_safety_car:,} further stops were made under a neutralisation and",
        "are excluded: they cost far less, and a simulator using a green-flag pit loss for a",
        "safety-car stop would get the most important decision in a race backwards.",
        "",
        f"**Pooled: {pit.pooled.seconds.value:.2f} s**"
        f" {_interval(pit.pooled.seconds, 2, signed=False)}",
        "",
        "| Circuit | Pit loss (s) | Interval | Own weight | Stops |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {entry.circuit} | {entry.seconds.value:.2f} |"
        f" {_interval(entry.seconds, 2, signed=False)} |"
        f" {_weight(entry.seconds)} | {entry.n_stops} |"
        for entry in sorted(pit.circuits, key=lambda item: -item.seconds.value)
    ]

    lines += ["", "## Neutralisations", ""]
    for kind in (params.safety_car.safety_car, params.safety_car.virtual_safety_car):
        hazard = kind.pooled.per_lap_probability
        lines += [
            f"### {kind.kind.replace('_', ' ').title()}",
            "",
            f"- **{hazard.value:.4f} per green lap** {_interval(hazard, signed=False)}"
            f" — {kind.pooled.n_deployments} deployments over"
            f" {kind.pooled.laps_at_risk:,} laps at risk",
            f"- Occurred in {kind.races_with_any} of {kind.n_races} races"
            f" ({kind.share_of_races:.0%}), {kind.pooled.expected_per_race:.2f} expected per race",
            "- Never observed in the training seasons, so its duration is unknown"
            if kind.duration_laps is None
            else (
                f"- Lasting {kind.duration_laps.value:.1f} laps"
                f" {_interval(kind.duration_laps, 1, signed=False)} on average"
            ),
            "",
        ]
    lines.append("")
    return "\n".join(lines)
